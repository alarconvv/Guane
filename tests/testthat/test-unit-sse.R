test_that('MuSSE helpers validate states, tables and roots', {
 d <- guane_test_data()
 expect_equal(guane_musse_names(2), c('lambda1', 'lambda2', 'mu1', 'mu2', 'q12', 'q21'))
 expect_error(guane_musse_names(9), 'two to eight observed states')
 st <- guane_musse_state_table(d$traits, 'locomotion_3state')
 expect_equal(st$RootWeight, rep(1 / 3, 3))
 expect_error(guane_musse_state_table(d$traits, 'locomotion_3state', 'State,Sampling,RootWeight\nflying,1,1'), 'each observed state exactly once')
 expect_error(guane_musse_state_table(d$traits, 'locomotion_3state', 'State,Sampling,RootWeight\nflying,0,.3\nswimming,1,.3\nwalking,1,.4'), 'sampling fractions')
 expect_error(guane_musse_state_table(d$traits, 'locomotion_3state', 'State,Sampling,RootWeight\nflying,1,.5\nswimming,1,.5\nwalking,1,.5'), 'sum to one')
 expect_error(guane_musse_fit(d$tree, d$traits, 'species', 'locomotion_3state', models = 'Equal transitions', root = 'EQUI', starts = 1), 'equilibrium roots are unavailable')
 expect_error(guane_musse_fit(d$tree, d$traits, 'species', 'locomotion_3state', models = 'None'), 'Select supported MuSSE models.')
 sym <- guane_musse_constraint(guane_musse_parameters(d$tree, 3), 'Symmetric transitions', 3)
 expect_equal(sym$table$Group[sym$table$Parameter == 'q21'], 'q12')
})

test_that('QuaSSE helpers validate rate functions, data, grid and parameter tables', {
 d <- guane_test_data()
 expect_equal(guane_quasse_function('Constant')(1:3, 2), c(2, 2, 2))
 expect_error(guane_quasse_function('Linear'), 'Select supported QuaSSE rate functions.')
 expect_error(guane_quasse_data(d$tree, d$traits, 'species', 'habitat_binary'), 'finite, nonconstant continuous observations')
 expect_error(guane_quasse_data(d$tree, d$traits, 'species', 'body_mass', error = 0), 'standard errors must be positive')
 expect_error(guane_quasse_data(d$tree, d$traits, 'species', 'body_mass', error_column = 'nope'), 'valid measurement-error column')
 expect_error(guane_quasse_data(d$tree, d$traits[-1, ], 'species', 'body_mass'), 'Match tree and trait taxa')
 q <- guane_quasse_data(d$tree, d$traits, 'species', 'body_mass')
 expect_equal(names(q$states), q$tree$tip.label)
 expect_error(guane_quasse_control(q, nx = 100), 'Invalid QuaSSE integration settings.')
 expect_error(guane_quasse_control(q, xmid = 1e6), 'grid must contain all observed trait values')
 ctl <- guane_quasse_control(q)
 expect_equal(ctl$xmid, mean(range(q$states)))
 tab <- guane_quasse_parameters(q, 'Sigmoid', 'Constant')
 expect_equal(tab$Parameter, c('l.y0', 'l.y1', 'l.xmid', 'l.r', 'm.c', 'drift', 'diffusion'))
 expect_equal(tab$Fixed[tab$Parameter == 'drift'], 0)
 expect_error(guane_quasse_parameters(q, text = 'x,y\n1,2'), 'Invalid QuaSSE parameter table.')
 expect_error(guane_quasse_likelihood(q, 'Constant', 'Constant', ctl, sampling = 2), 'Invalid QuaSSE sampling or root settings.')
 expect_error(guane_quasse_fit(d$tree, d$traits, 'species', 'body_mass', starts = 0), 'Invalid QuaSSE optimizer settings.')
})

test_that('guane_quasse_fit fits a constant-rate model on log body mass', {
