# Unit tests: state-dependent speciation and extinction (R/core_mod_sse*.R).

test_that('guane_bisse_data codes the explicit state 0 and validates inputs', {
 d <- guane_test_data()
 z <- guane_bisse_data(d$tree, d$traits, 'species', 'habitat_binary', 'terrestrial')
 expect_equal(z$mapping$State, c('terrestrial', 'aquatic'))
 expect_equal(unname(z$states), as.integer(d$traits$habitat_binary[match(d$tree$tip.label, d$traits$species)] != 'terrestrial'))
 expect_equal(sum(z$mapping$Count), length(d$tree$tip.label))
 expect_error(guane_bisse_data(d$tree, d$traits, 'species', 'habitat_binary', 'marine'), 'explicit state 0')
 expect_error(guane_bisse_data(d$tree, d$traits, 'species', 'locomotion_3state', 'walking'), 'two observed states')
 expect_error(guane_bisse_data(d$tree, d$traits[-1, ], 'species', 'habitat_binary', 'terrestrial'), 'Match tree and trait taxa')
 expect_error(guane_bisse_data(d$tree, d$traits, 'species', 'species', 'Sp01'), 'taxon column and a binary trait')
 small <- ape::keep.tip(d$tree, d$tree$tip.label[1:3])
 expect_error(guane_bisse_data(small, d$traits, 'species', 'habitat_binary', 'terrestrial'), 'at least four tips')
})

test_that('BiSSE constraint templates tie or fix the documented parameters', {
 d <- guane_test_data()
 tab <- guane_bisse_parameters(d$tree)
 expect_equal(tab$Parameter, guane_bisse_names())
 tid <- guane_bisse_constraint(tab, 'Trait-independent diversification')
 expect_setequal(tid$free, c('lambda0', 'mu0', 'q01', 'q10'))
 noext <- guane_bisse_constraint(tab, 'No extinction')
 expect_equal(noext$table$Fixed[3:4], c(0, 0))
 expect_false(any(c('mu0', 'mu1') %in% noext$free))
 expect_equal(guane_sse_expand(c(lambda0 = 1, mu0 = .2, q01 = .1, q10 = .3)[tid$free], tid),
  c(lambda0 = 1, lambda1 = 1, mu0 = .2, mu1 = .2, q01 = .1, q10 = .3))
 expect_error(guane_bisse_constraint(tab, 'Everything'), 'Select supported BiSSE models.')
 expect_error(guane_bisse_parameters(d$tree, 'a,b\n1,2'), 'Invalid BiSSE parameter table.')
 txt <- paste(c('Parameter,Group,Fixed,Start,Lower,Upper', paste0(tab$Parameter, ',', tab$Group, ',,', -1, ',0,10')), collapse = '\n')
 expect_error(guane_bisse_parameters(d$tree, txt), 'finite nonnegative bounds')
})

test_that('guane_bisse_fit fits one cheap BiSSE model on habitat_binary', {
 d <- guane_test_data()
 r <- guane_bisse_fit(d$tree, d$traits, 'species', 'habitat_binary', 'terrestrial', models = 'Trait-independent diversification', starts = 1, slices = FALSE)
 expect_equal(r$comparison$Model, 'Trait-independent diversification')
 expect_true(r$comparison$Converged)
 expect_true(is.finite(r$comparison$LogLik))
 p <- r$fits[[1]]$par
 expect_equal(unname(p['lambda0']), unname(p['lambda1']))
 expect_equal(unname(p['mu0']), unname(p['mu1']))
 expect_true(all(p >= 0))
 # A single candidate never receives an AIC weight.
 expect_true(is.na(r$comparison$Weight))
 expect_true(any(grepl('exploratory', r$warnings)))
 # Refit reproduces the same likelihood (deterministic starts, no RNG).
 again <- guane_bisse_fit(d$tree, d$traits, 'species', 'habitat_binary', 'terrestrial', models = 'Trait-independent diversification', starts = 1, slices = FALSE)
 expect_equal(again$comparison$LogLik, r$comparison$LogLik)
})

