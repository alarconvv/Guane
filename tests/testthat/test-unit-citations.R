test_that('every analysis has translated citation comments with official references', {
 for(key in unlist(guane_cards,use.names=FALSE)) for(lang in c('en','es','pt')) {
  info <- guane_analysis_citation(key,list(),lang)
  comments <- guane_citation_comments(key,list(),lang)
  expect_true(all(startsWith(comments,'# ')))
  expect_length(parse(text=comments),0)
  expect_true(any(grepl(info$sentence,comments,fixed=TRUE)))
  expect_match(info$references[1], 'https://github.com/alarconvv/Guane',fixed=TRUE)
  expect_identical(info$references[2],paste(format(utils::citation('ape'),style='text'),collapse='\n'))
 }
