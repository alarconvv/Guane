# Run from BioRxav: Rscript --vanilla scripts/04_verify_interface_terminal.R
out <- 'results/interface-test-2026-11-11'
repo <- '/Users/vivianaromeroalarcon/My Drive/PROJECTS/G4_PlatformsAndReproducibility/G4P3_Guane/Guane'
stopifnot(dir.exists(out))
pkgload::load_all(repo, quiet=TRUE)
tree <- ape::read.tree('data/raw/geospiza-tree-14tips.nwk')
traits <- read.csv('data/raw/geospiza-traits-distributed.csv',check.names=FALSE)
excluded <- setdiff(tree$tip.label,traits$taxon)
stopifnot(identical(excluded,'olivacea'))
tree <- ape::keep.tip(tree,traits$taxon)
traits <- traits[match(tree$tip.label,traits$taxon),]
ns <- asNamespace('guane')
signal <- ns$guane_signal(tree,traits,'taxon','beakD',seed=20261201,nsim=999)
pgls <- ns$guane_pgls(tree,traits,'taxon','beakD','wingL',model='BM',method='REML')
write.csv(signal,file.path(out,'terminal-signal.csv'),row.names=FALSE)
write.csv(pgls$coefficients,file.path(out,'terminal-pgls.csv'),row.names=FALSE)
write.csv(pgls$points,file.path(out,'terminal-residuals.csv'),row.names=FALSE)
s <- new.env(parent=globalenv())
pdf(file.path(out,'signal-export-terminal.pdf'))
source(file.path(out,'signal-export.R'),local=s)
dev.off()
p <- new.env(parent=globalenv())
pdf(file.path(out,'pgls-live-code-terminal.pdf'))
source(file.path(out,'pgls-live-code.R'),local=p)
dev.off()
near <- function(a,b) isTRUE(all.equal(a,b,tolerance=1e-8,check.attributes=FALSE))
stopifnot(near(s$result,signal),near(p$result$coefficients,pgls$coefficients),near(p$result$points,pgls$points))
stopifnot(near(s$inputs$tree$edge.length,tree$edge.length),identical(s$inputs$tree$tip.label,tree$tip.label),near(p$traits,traits),identical(p$tree$tip.label,tree$tip.label))
write.csv(s$result,file.path(out,'signal-export-refit.csv'),row.names=FALSE)
write.csv(p$result$coefficients,file.path(out,'pgls-live-code-refit.csv'),row.names=FALSE)
# Compare the GUI's observed five-decimal display with full terminal precision.
gui_signal <- c(.64307,.03904,.74572,.16762)
terminal_signal <- c(signal$Estimate[1],signal$P_value[1],signal$Estimate[2],signal$P_value[2])
gui_coefficients <- matrix(c(-10.95301,1.50097,-14.25662,-7.64941,.00002,3.03848,.35545,2.25613,3.82083,.00000),nrow=2,byrow=TRUE)
terminal_coefficients <- as.matrix(pgls$coefficients[-1])
stopifnot(max(abs(gui_signal-terminal_signal))<=5.1e-6,max(abs(gui_coefficients-terminal_coefficients))<=5.1e-6)
checks <- data.frame(Check=c('Original input mismatch is olivacea','13 matched species','GUI signal values match at displayed precision','GUI PGLS table matches at displayed precision','Downloaded signal script refits to terminal result','PGLS Live Code Mirror refits to terminal result','PGLS normalized residuals agree','GUI embedded prepared inputs agree'),Status='PASS')
write.csv(checks,file.path(out,'verification-checks.csv'),row.names=FALSE)
saveRDS(list(signal=signal,pgls=pgls,signal_export=s$result,pgls_live_code=p$result),file.path(out,'verified-fits.rds'))
capture.output(sessionInfo(),file=file.path(out,'terminal-sessionInfo.txt'))
cat('\nPASS: GUI display, terminal package calls and interface-generated scripts agree.\n')
print(checks,row.names=FALSE)
